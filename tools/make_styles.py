#!/usr/bin/env python3
"""
Turn a letter-lab export into js/styles.js.

    python3 tools/make_styles.py path/to/microdose-letters.json

Uses only the Python standard library. Every stroke that has a letter assigned (M, I, C, R, O, D, O, S, E)
is included; strokes left unassigned or marked "skip" are left out. Each version's pen (pink, blue, red or
black) is worked out from the ink colour the extraction script recorded. The author comes from the lab's
Author field and is what the page shows in the corner.

Afterwards, check js/config.js: every author printed at the end should have a line under `links`
(the link can stay empty).
"""
import colorsys
import json
import pathlib
import sys


def pen(ink):
    """Name the pen from the ink colour the photo extraction measured."""
    if not ink:
        return "pink"
    r, g, b = (int(ink[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    if v < 0.36 and s < 0.4:          # dark and greyish: a black (or very dark) pen
        return "black"
    h *= 360
    if 180 <= h < 290:
        return "blue"
    if 290 <= h < 345:
        return "pink"
    return "red"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    out = pathlib.Path(__file__).resolve().parent.parent / "js" / "styles.js"
    lines, authors, pens = [], {}, {}
    for w in data["words"]:
        strokes = [[s["d"], s["letter"]] for s in w["strokes"] if isinstance(s.get("letter"), int) and 0 <= s["letter"] <= 8]
        if not strokes:
            print(f"skipping {w['id']} ({w.get('name', '')}): no letters assigned")
            continue
        if w.get("reviewed") is False:
            print(f"note: {w['id']} is not marked as checked in the lab (included anyway)")
        author = (w.get("author") or "").strip()
        p = pen(w.get("ink"))
        lines.append(json.dumps({"id": w["id"], "pen": p, "a": author, "s": strokes}, separators=(",", ":")))
        key = author or "(no author)"
        authors[key] = authors.get(key, 0) + 1
        pens[p] = pens.get(p, 0) + 1
    header = (
        "/* The lettering: every version of the title as pen strokes grouped by letter (path, letter 0 to 8),\n"
        "   with the pen it was drawn in and who drew it.\n"
        "   Generated by tools/make_styles.py from a letter-lab export. Please don't edit by hand. */\n"
    )
    out.write_text(header + "window.MICRODOSE_STYLES = [\n" + ",\n".join(lines) + "\n];\n", encoding="utf-8")
    print(f"wrote {out} with {len(lines)} versions")
    print("  pens:    " + ", ".join(f"{k} {v}" for k, v in sorted(pens.items())))
    print("  authors: " + ", ".join(f"{k} {v}" for k, v in sorted(authors.items())))
    print("Every author above should have a line under `links` in js/config.js.")


if __name__ == "__main__":
    main()
