#!/usr/bin/env python3
"""
Turn the pictures in assets/smileys/ into js/smileys.js.

    python3 tools/make_smileys.py

A static site can't list a folder, so the page reads this list instead. Run it again whenever you add, remove or
rename a picture. The feeling shown on the sticker is the file's name: awesome.png becomes "awesome", and
"very-sleepy.png" or "very_sleepy.png" becomes "very sleepy". Only the pictures directly in assets/smileys/ are
used; sub-folders (such as originals/) are left alone.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
folder = root / "assets" / "smileys"
kinds = {".png", ".webp", ".jpg", ".jpeg", ".gif", ".svg"}

files = sorted(p.name for p in folder.iterdir() if p.is_file() and p.suffix.lower() in kinds)
if not files:
    raise SystemExit("No pictures found in " + str(folder))

lines = ["/* Generated by tools/make_smileys.py from the pictures in assets/smileys/. Do not edit by hand. */",
         "window.MICRODOSE_SMILEYS = ["]
lines += ["  'assets/smileys/%s'%s" % (f, "," if i < len(files) - 1 else "") for i, f in enumerate(files)]
lines.append("];")
(root / "js" / "smileys.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("js/smileys.js: %d pictures" % len(files))
for f in files:
    print("  " + f)
